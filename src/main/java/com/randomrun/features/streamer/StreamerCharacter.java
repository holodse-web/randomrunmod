    public record Phrase(String text, String sound, int ms) {}


    public record Look(Body body, String texture) {
        public enum Body { NORMAL, CHUBBY, SLIM, STRONG }
    }

    private final String nickname;
    private final Look look;
    private final Map<Event, List<Phrase>> phrases;

    StreamerCharacter(String nickname, Look look, Map<Event, List<Phrase>> phrases) {
        this.nickname = nickname;
        this.look = look;
        this.phrases = phrases;
    }

    public String nickname() { return nickname; }
    public Look look() { return look; }

    private net.minecraft.world.entity.player.PlayerSkin skin;


    public net.minecraft.world.entity.player.PlayerSkin skin() {
        if (skin == null) skin = StreamerSkin.load(look.texture());
        return skin;
    }

    public List<Phrase> phrases(Event event) {
        return phrases.getOrDefault(event, List.of());
    }


    public int phraseCount() {
        java.util.Set<String> sounds = new java.util.HashSet<>();
        for (List<Phrase> list : phrases.values()) for (Phrase phrase : list) sounds.add(phrase.sound());
        return sounds.size();
    }


    public int momentCount() {
        return phrases.size();
    }

    public static String textForSound(String sound) {
        if (sound == null || sound.isEmpty()) return null;
        for (StreamerCharacter character : values()) {
            for (List<Phrase> list : character.phrases.values()) {
                for (Phrase phrase : list) if (sound.equals(phrase.sound())) return phrase.text();
            }
        }
        return null;
    }

    public static StreamerCharacter byName(String name) {
        for (StreamerCharacter character : values()) if (character.name().equals(name)) return character;
        return null;
    }

    private static Phrase p(String text, String sound, int ms) {
        return new Phrase(text, sound, ms);
    }

    @SuppressWarnings("unchecked")
    private static Map<Event, List<Phrase>> phrases(Object... pairs) {
        Map<Event, List<Phrase>> map = new EnumMap<>(Event.class);
        for (int i = 0; i < pairs.length; i += 2) map.put((Event) pairs[i], (List<Phrase>) pairs[i + 1]);
        return map;
    }
